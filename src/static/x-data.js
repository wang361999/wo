/* Web 安全色：RGB 各取 00/33/66/99/CC/FF */
const webSafe = (() => {
  const a = ['00', '33', '66', '99', 'CC', 'FF'], out = [];
  for (const r of a) for (const g of a) for (const b of a) {
    const hex = '#' + r + g + b;
    out.push(`${hex}|rgb(${parseInt(r,16)},${parseInt(g,16)},${parseInt(b,16)})|${r}|${g}|${b}`);
  }
  return out.join('\n');
})();

